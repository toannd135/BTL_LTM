-- Nhat ky kiem toan trong CSDL (song song voi tep audit.log) va cap quyen dac biet co thoi han (break-glass).
CREATE TABLE audit_events (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ts       TEXT NOT NULL,
    session  TEXT,
    ip       TEXT,
    username TEXT,
    event    TEXT NOT NULL,
    result   TEXT NOT NULL CHECK (result IN ('OK', 'FAIL')),
    detail   TEXT
);
CREATE INDEX idx_audit_ts ON audit_events(ts);
CREATE INDEX idx_audit_user ON audit_events(username);
CREATE INDEX idx_audit_event ON audit_events(event);
CREATE TABLE breakglass_grants (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username   TEXT NOT NULL,
    scope      TEXT NOT NULL,
    reason     TEXT NOT NULL,
    granted_by TEXT NOT NULL,
    created_at TEXT NOT NULL DEFAULT to_char(now() AT TIME ZONE 'UTC', 'YYYY-MM-DD HH24:MI:SS'),
    expires_at TEXT NOT NULL,
    revoked    INTEGER NOT NULL DEFAULT 0 CHECK (revoked IN (0, 1))
);
CREATE INDEX idx_breakglass_user ON breakglass_grants(username);
